const delay = (ms: number) => new Promise((resolve) => setTimeout(resolve, ms));

export async function fetchTokens(): Promise<Token[]> {
  await delay(650 + Math.random() * 400);
  // Small chance to surface error states for the error boundary path
  if (Math.random() < 0.05) {
    throw new Error("Transient feed error. Please retry.");
  }
  return seedTokens.map((t) => ({ ...t }));
}

export const getTokenById = (tokens: Token[], id: string | null) => tokens.find((t) => t.id === id);
